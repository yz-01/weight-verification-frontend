export type FileAction = "preview" | "print" | "save" | "share";

export interface FileSource {
  /** Fetches the file; every action then works on what this returned. */
  load: () => Promise<File>;
  /**
   * Only where the server records that a file left the system (an evidence
   * package's 「已导出」, D-148): the same stored file, fetched so that the
   * export or the send is noted. Preview and print use `load` and note
   * nothing - looking at a file is not taking it out.
   */
  loadToSend?: () => Promise<File>;
  /** The heading on the preview and the share sheet. */
  title: string;
  /**
   * Where the record opens in the system, for colleagues who sign in: copied
   * or put in the message beside the file (2026-10 C11).
   */
  link?: string;
  /**
   * What the operation log row names (JB27): the business item (the title
   * when not given), its project, the record, the 「报表导出历史」 row. The
   * server's own answer fills the project and history row where it knows
   * them (`fileMeta`).
   */
  subject?: string;
  project?: string;
  recordKind?: string;
  recordId?: string;
  reportExport?: string;
  /**
   * The server keeps each real export in 「报表导出历史」 (a list or report
   * generated by `ExportButton`): a print, export or send taken from the
   * preview fetches it again, so it is kept and the log row points at it.
   */
  exportedOnServer?: boolean;
}

/** Share2, not Send: 「发送给顾问」 and other formal sends already use Send. */
export const FILE_ACTION_ICONS = {
  preview: Eye,
  print: Printer,
  save: Download,
  share: Share2,
} as const;

interface Held {
  file: File;
  title: string;
  link?: string;
  allowSave: boolean;
  /** Where the file came from: fetched again, and named in the log (JB27). */
  source: FileSource;
  /** JB25: why print / export / send are off; only the preview works. */
  blockedReason?: string;
}

const LEAVES: readonly FileAction[] = ["save", "share"];

/** The log's word for each action that takes a file out (JB27). */
export const FILE_ACTION_TYPE: Record<Exclude<FileAction, "preview">, FileActionType> = {
  print: "PRINT",
  save: "DOWNLOAD",
  share: "SEND",
};

/** The log row's details for `file`, from where it came and what the server said. */
export function fileActionDetails(source: FileSource, file: File, title: string): FileActionDetails {
  const meta = fileMeta(file);
  return {
    subject: source.subject || title,
    file_name: file.name,
    project: source.project ?? meta.project,
    report_export: source.reportExport ?? meta.reportExport,
    record_kind: source.recordKind,
    record_id: source.recordId,
    link: source.link,
  };
}

/**
 * Run 预览 / 打印 / 导出 / 发送 on a file, and draw the dialogs they open.
 *
 * Render `element` once, anywhere in the caller.
 */
export function useFileActions() {
  const t = useTranslations("fileActions");
  const [busy, setBusy] = useState<string | null>(null);
  const [viewing, setViewing] = useState<Held | null>(null);
  const [sending, setSending] = useState<Held | null>(null);

  /** Fetch with a spinner; null when it failed (and the person was told). */
  const fetchWith = useCallback(
    async (load: () => Promise<File>, key: string): Promise<File | null> => {
      setBusy(key);
      try {
        return await load();
      } catch (error) {
        // A refusal from the server has already been toasted in the reader's
        // language; anything else gets a plain sentence, not silence.
        if (!(error instanceof ApiError) && !(error instanceof DOMException && error.name === "AbortError")) {
          toast.error(t("failed"));
        }
        return null;
      } finally {
        setBusy(null);
      }
    },
    [t],
  );

  /** Do it, on the file in hand: the PIN and the log are already behind. */
  const perform = useCallback(
    async (action: Exclude<FileAction, "preview">, held: Held) => {
      if (action === "save") {
        saveFile(held.file);
      } else if (action === "print") {
        if (!(await printFile(held.file))) {
          // A phone that cannot print from the page: the preview, where the
          // phone's own viewer prints it.
          setViewing(held);
          toast.info(t("printFromViewer"));
        }
      } else {
        const outcome = await shareFile(held.file, held.title);
        if (outcome === "shared") toast.success(t("shared"));
        else if (outcome !== "cancelled") setSending(held);
      }
    },
    [t],
  );

  /**
   * 打印 / 导出 / 发送: on the desktop, the PIN first (closing it does
   * nothing), then the file - fetched again where the server keeps or notes
   * each one - then its log row, then the action. On the phone, as before.
   */
  const leave = useCallback(
    async (
      action: Exclude<FileAction, "preview">,
      source: FileSource,
      inHand: File | null,
      options: { key: string; allowSave: boolean },
    ) => {
      const signs = signsFileActions();
      const type = FILE_ACTION_TYPE[action];
      let grant: string | null = null;
      if (signs) {
        setBusy(options.key);
        grant = await authorizeFileAction(type);
        setBusy(null);
        if (!grant) return;
      }
      const sends = LEAVES.includes(action) && Boolean(source.loadToSend);
      let file = inHand;
      if (!file || sends || (signs && source.exportedOnServer)) {
        const load = sends ? source.loadToSend! : source.load;
        file = await fetchWith(() => withFileFetch(grant ? { grant } : null, load), options.key);
        if (!file) return;
      }
      const title = source.title || file.name.replace(/\.[^.]+$/, "");
      if (signs) {
        setBusy(options.key);
        const written = await recordFileAction(type, fileActionDetails(source, file, title), grant);
        setBusy(null);
        if (!written) return;
      }
      await perform(action, { file, title, link: source.link, allowSave: options.allowSave, source });
    },
    [fetchWith, perform],
  );

  /** One action on a file already in hand (the preview's own buttons). */
  const act = useCallback(
    async (action: FileAction, held: Held) => {
      if (action === "preview") {
        setViewing(held);
        return;
      }
      if (held.blockedReason) return;
      await leave(action, held.source, held.file, { key: action, allowSave: held.allowSave });
    },
    [leave],
  );

  /** Fetch the file, then run the action on it. `key` names the spinner. */
  const run = useCallback(
    async (
      action: FileAction,
      source: FileSource,
      options: { key?: string; allowSave?: boolean; blockedReason?: string } = {},
    ) => {
      if (busy) return;
      const key = options.key ?? action;
      const allowSave = options.allowSave ?? true;
      // JB25: not yet confirmed - looked at, never taken out.
      if (options.blockedReason && action !== "preview") return;
      if (action !== "preview") {
        await leave(action, source, null, { key, allowSave });
        return;
      }
      // Looking is not taking it out: no PIN, no history row (JB27).
      const file = await fetchWith(
        () => withFileFetch(signsFileActions() ? { preview: true } : null, source.load),
        key,
      );
      if (!file) return;
      setViewing({
        file,
        title: source.title || file.name.replace(/\.[^.]+$/, ""),
        link: source.link,
        allowSave,
        source,
        blockedReason: options.blockedReason,
      });
    },
    [busy, fetchWith, leave],
  );

  const element = (
    <>
      {viewing ? (
        <FileViewerDialog
          held={viewing}
          busy={Boolean(busy)}
          onAct={(action) => void act(action, viewing)}
          onClose={() => setViewing(null)}
        />
      ) : null}
      {sending ? <ShareFileDialog held={sending} onClose={() => setSending(null)} /> : null}
    </>
  );

  return { busy, run, element };
}

/** The four, in their one order. Printing is for PDFs only. */
export function fileActionsFor(format: "pdf" | "sheet", allowSave = true): FileAction[] {
  const all: FileAction[] = format === "pdf" ? ["preview", "print", "save", "share"] : ["preview", "save", "share"];
  return allowSave ? all : all.filter((action) => action !== "save");
}

/**
 * 预览 · 打印 · 导出 · 发送 as four buttons, for one file - a record's PDF in
 * the top right of its detail, or a dialog's own file.
 */
export function FileActionButtons({
  source,
  allowSave = true,
  disabled,
  disabledReason,
  className,
  label,
  labelHint,
  blockedReason,
  omit,
}: {
  source: FileSource;
  /** False where the person may look at the file but not export it. */
  allowSave?: boolean;
  /**
   * Actions drawn by the caller instead: an evidence package's 「发送」 is its
   * own 「对外分享（WhatsApp / 电邮）」, which writes the share down (JB51).
   */
  omit?: readonly FileAction[];
  /**
   * JB25 (客户 10-26 事项 1): 「确认归档前，不能对外转发、导出、打印或生成分享
   * 链接」 - set, print / export / send are off with this reason; preview stays.
   */
  blockedReason?: string;
  disabled?: boolean;
  disabledReason?: string;
  className?: string;
  /**
   * What the four buttons act on, said once before them - a record's
   * 「完整证据 PDF」 (2026-10-10, 审批证据完整性), so nobody mistakes it for
   * the bare form. `labelHint` says what is inside, on hover.
   */
  label?: string;
  labelHint?: string;
}) {
  const t = useTranslations("fileActions");
  const { busy, run, element } = useFileActions();
  return (
    <>
      <div className={cn("contents", className)} data-slot="file-actions">
        {label ? (
          <span
            className="col-span-full inline-flex items-center gap-1 self-center text-xs font-medium text-muted-foreground"
            title={labelHint}
            data-slot="file-actions-label"
          >
            <FileText className="size-3.5" aria-hidden />
            {label}
          </span>
        ) : null}
        {fileActionsFor("pdf", allowSave).filter((action) => !omit?.includes(action)).map((action) => {
          const Icon = FILE_ACTION_ICONS[action];
          return (
            <Button
              key={action}
              type="button"
              size="sm"
              variant="outline"
              data-slot={`file-action-${action}`}
              disabled={disabled || Boolean(busy) || (Boolean(blockedReason) && action !== "preview")}
              disabledReason={
                disabled
                  ? disabledReason
                  : blockedReason && action !== "preview"
                    ? blockedReason
                    : busy
                      ? t("preparing")
                      : undefined
              }
              title={action === "share" ? t("shareHint") : undefined}
              onClick={() => void run(action, source, { allowSave, blockedReason })}
            >
              {busy === action ? <Loader2 className="size-3.5 animate-spin" /> : <Icon className="size-3.5" />}
              {t(action)}
            </Button>
          );
        })}
      </div>
      {element}
    </>
  );
}

